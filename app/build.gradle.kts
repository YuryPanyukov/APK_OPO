import java.io.FileInputStream
import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.ksp)
}

// ---------------------------------------------------------------------------
// Подпись релиза
// Секреты не храним в репозитории: rootProject/keystore.properties (см. .gitignore).
// Ключи: storeFile (относительно корня проекта), storePassword, keyAlias, keyPassword.
// Если файла нет — релиз собирается без подписи (unsigned) для локальной проверки.
// ---------------------------------------------------------------------------
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}
val hasReleaseKeystore = keystorePropertiesFile.exists()

// ---------------------------------------------------------------------------
// Версии. Переопределяются из командной строки или CI:
//   ./gradlew assembleRelease -PappVersionCode=42 -PappVersionName=1.2.3
// ---------------------------------------------------------------------------
val appVersionCode = (findProperty("appVersionCode") as String?)?.toIntOrNull() ?: 1
val appVersionName = (findProperty("appVersionName") as String?) ?: "1.0"

android {
    namespace = "code_sys.apkopo"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "code_sys.apkopo"
        minSdk = 24
        targetSdk = 37
        versionCode = appVersionCode
        versionName = appVersionName

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            if (hasReleaseKeystore) {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Новый DSL AGP 9: включает R8 (shrinking + обфускация) и
            // оптимизацию ресурсов. Заменяет isMinifyEnabled/isShrinkResources.
            optimization {
                enable = true
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (hasReleaseKeystore) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
}

